files=[l.strip() for l in open('/tmp/bio_src.txt')]
out={k:[] for k in B}
for k,title in books:
    f=[x for x in files if k in x][0]
    raw=re.sub(r'\n~~',' ',open('/tmp/oiti/'+f,encoding='utf-8').read())
    L=[norm(re.sub(r'PageV\d+P\d+|ms\d+|[#|*()\[\]\d\-–.:«»"]',' ',l)).split()[:9] for l in raw.split('\n') if l.startswith('#') and not l.startswith('#META')]
    for key in W[k].split('|'):
        assert key in B,key
        hit=False
        for kk in B[key][1]:
            w=norm(kk).split()
            if any(words[i:i+len(w)]==w for words in L for i in range(0,6)): hit=True;break
        if hit: out[key].append(title)
        else: print('NOT CONFIRMED',k,key)
json.dump(out,open('/tmp/bio/sources.json','w'),ensure_ascii=False)
print(sum(1 for v in out.values() if v),'poets with sources')
