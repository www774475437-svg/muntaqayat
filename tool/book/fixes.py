# rhyme letter for every selection (same rule as build_poems.py)
MARKS = re.compile('[ً-ٰٟۡؐ-ؚ]')
def rhyme(lines):
    s = re.sub(r'[^ء-ي]', '', MARKS.sub('', lines[-1][-1]))
    s = s.rstrip('اويى') if len(s) > 2 else s
    if s.endswith('ه') and len(s) > 2 and s[-2] in 'اويى':
        s = s[:-2]
    c = s[-1:] if s else ''
    return {'ة': 'ت', 'ى': 'ي', 'أ': 'ء', 'إ': 'ء', 'ؤ': 'ء', 'ئ': 'ء', 'آ': 'ء'}.get(c, c)
